let currentLang = "en";

export function setLang(lang) {
  if (LANGUAGES[lang]) currentLang = lang;
  try { localStorage.setItem("mt_lang", lang); } catch {}
}

export function getLang() {
  try {
    const stored = localStorage.getItem("mt_lang");
    if (stored && LANGUAGES[stored]) { currentLang = stored; return stored; }
  } catch {}
  return currentLang;
}

export function t(key) {
  return LANGUAGES[currentLang]?.[key] || LANGUAGES.en[key] || key;
}

