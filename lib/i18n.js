const LangContext = createContext(null);

const RTL_LOCALES = new Set(["ar"]);

export function localeDir(lang) {
  return RTL_LOCALES.has(lang) ? "rtl" : "ltr";
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem("mt_lang") || "en"; } catch { return "en"; }
  });

  useEffect(() => {
    try {
      const root = document.documentElement;
      root.lang = lang;
      root.dir = localeDir(lang);
    } catch {}
  }, [lang]);

  const setLang = useCallback((newLang) => {
    if (LANGUAGES[newLang]) {
      setLangState(newLang);
      try { localStorage.setItem("mt_lang", newLang); } catch {}
    }
  }, []);

  const t = useCallback((key, params = {}) => {
    let str = LANGUAGES[lang]?.[key] || LANGUAGES.en[key] || key;
    if (typeof str !== "string") str = key;
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
    });
    return str;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}

// Locale-aware formatting. `lang` is the active locale id (e.g. "ar", "fr").
// Falls back to the browser default when Intl rejects the tag.
export function formatDate(value, lang, opts = {}) {
  try { return new Intl.DateTimeFormat(lang || undefined, opts).format(new Date(value)); }
  catch { return new Date(value).toLocaleDateString(); }
}

export function formatTime(value, lang, opts = { hour: "numeric", minute: "2-digit" }) {
  try { return new Intl.DateTimeFormat(lang || undefined, opts).format(new Date(value)); }
  catch { return new Date(value).toLocaleTimeString(); }
}

export function formatNumber(value, lang, opts = {}) {
  try { return new Intl.NumberFormat(lang || undefined, opts).format(value); }
  catch { return String(value); }
}

// Locale-independent day key (YYYY-MM-DD) in local time, or a given IANA zone.
// Replaces the `toLocaleDateString("en-CA")` hack.
export function dayKey(value = new Date(), tz) {
  const d = value instanceof Date ? value : new Date(value);
  const opts = { year: "numeric", month: "2-digit", day: "2-digit" };
  if (tz) opts.timeZone = tz;
  try {
    const parts = new Intl.DateTimeFormat("en-CA", opts).formatToParts(d);
    const get = k => parts.find(p => p.type === k)?.value || "";
    return `${get("year")}-${get("month")}-${get("day")}`;
  } catch {
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, "0");
    const day = String(d.getDate()).padStart(2, "0");
    return `${y}-${m}-${day}`;
  }
}

